# -----------------------------------------------------------------------------
# ab recall --index [--check] — write .platform/CARDS.md, a one-line-per-card map.
#
# For people whose agents run WITHOUT Agentboard: the entry files tell them to read
# this file, then open the one card they need. Plain markdown, committed with the
# cards. --check exits 1 (and writes nothing) when the file is missing or stale.
# Deliberately outside domains/ so it is never mistaken for a card. Pure bash 3.2.
# -----------------------------------------------------------------------------

_recall_index_body() {
  local f slug repos
  printf '# Cards\n\nOne card per feature, in `.platform/domains/`. Open the one that matches your task; do not read them all.\nGenerated by `ab recall --index` — do not edit by hand.\n\n'
  while IFS= read -r f; do
    [[ -n "$f" ]] || continue
    slug="$(basename "$f" .md)"; repos="$(_recall_repos "$f")"
    printf -- '- `domains/%s.md`%s — %s\n' "$slug" "${repos:+ [$repos]}" "$(_recall_summary "$f")"
  done < <(_recall_cards)
}

cmd_recall_index() {
  local out="./.platform/CARDS.md" tmp body check=0
  [[ "${1:-}" == "--check" ]] && check=1
  body="$(_recall_index_body)"
  if (( check )); then
    [[ -f "$out" && "$(cat "$out")" == "$body" ]] && { ok "CARDS.md is current."; return 0; }
    warn "CARDS.md is missing or stale — run: ab recall --index"; return 1
  fi
  tmp="$(mktemp)"; printf '%s\n' "$body" > "$tmp" && mv "$tmp" "$out"
  ok "Wrote $out ($(printf '%s\n' "$body" | grep -c '^- ' || true) cards)"
}
